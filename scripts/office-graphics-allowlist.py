#!/usr/bin/env python3
"""Generate finite S1934 chart/SmartArt rules from the pinned MIT Open XML SDK.

Source: dotnet/Open-XML-SDK 431ab05cf160248cc3885a4a766026d4f8243792.
Usage: office-graphics-allowlist.py SDK_DATA_SCHEMAS OUTPUT_DIRECTORY
Run rustfmt on the generated files. Active/source/extension elements are excluded
explicitly; the runtime removes them or narrowly validates the SmartArt cache link.
"""
import json
from pathlib import Path
import sys

source, output = map(Path, sys.argv[1:])
families = {
    "chart": ["schemas_openxmlformats_org_drawingml_2006_chart.json", "schemas_microsoft_com_office_drawing_2012_chartStyle.json"],
    "diagram": ["schemas_openxmlformats_org_drawingml_2006_diagram.json", "schemas_microsoft_com_office_drawing_2008_diagram.json"],
}
excluded = {
    "chart": set("f strRef numRef multiLvlStrRef externalData pivotSource pivotFmts printSettings headerFooter protection userShapes extLst ext".split()),
    "diagram": set("title desc catLst cat".split()),
}
for family, files in families.items():
    rows, children = {}, {}
    for filename in files:
        schema = json.loads((source / filename).read_text())
        types = {t["ClassName"]: t for t in schema["Types"]}
        def ancestry(t):
            base = types.get(t.get("BaseClass"))
            return ([t] if base is None else [*ancestry(base), t])
        for t in schema["Types"]:
            element = t["Name"].split("/")[-1].split(":")[-1]
            if not element or element in excluded[family]:
                continue
            key = schema["TargetNamespace"], element
            for inherited in ancestry(t):
                rows.setdefault(key, set()).update(a["QName"].split(":")[-1] for a in inherited.get("Attributes", []) if a["QName"].startswith(":"))
                children.setdefault(key, set()).update(c["Name"].split("/")[-1] for c in inherited.get("Children", []))
    if family == "chart":
        # CT_Tx and CT_SerTx share a QName but have different particles.
        # Keep them distinct rather than accepting the union of both types.
        children[("http://schemas.openxmlformats.org/drawingml/2006/chart", "tx")].discard("c:v")
    text = "// Generated by scripts/office-graphics-allowlist.py from the pinned MIT Open XML SDK.\n"
    for name, rules in [("rule", rows), *(([("children", children)]) if family == "chart" else [])]:
        text += f"pub(super) fn {name}(ns: &str, el: &str) -> Option<&'static str> {{\n    Some(match (ns, el) {{\n"
        for (ns, element), values in sorted(rules.items()):
            text += f"        ({json.dumps(ns)}, {json.dumps(element)}) => {json.dumps(' '.join(sorted(values)))},\n"
        text += "        _ => return None,\n    })\n}\n"
    if family == "chart":
        chart_schema = json.loads((source / files[0]).read_text())
        tx = {t["ClassName"]: " ".join(c["Name"].split("/")[-1].split(":")[-1] for c in t["Children"]) for t in chart_schema["Types"] if t["ClassName"] in ("SeriesText", "ChartText")}
        text += 'pub(super) fn tx_children(series: bool) -> &\'static str {\n    if series { ' + json.dumps(tx["SeriesText"]) + ' } else { ' + json.dumps(tx["ChartText"]) + ' }\n}\n'
    (output / f"{family}_allowlist.rs").write_text(text)
